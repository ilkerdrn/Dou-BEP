/** v2.49 isolated forced-choice consonant-identification exercise. This is a toy
 * acoustic laboratory with hardcoded short sound stimuli, not a validated speech test.
 * No identifier, audio recording, timestamps, text input, APIs, persistence or network.
 */
export const PAIRS=Object.freeze([
 Object.freeze({id:'s-sh',words:Object.freeze(['Sasa','Şaşa'])}),
 Object.freeze({id:'m-n',words:Object.freeze(['Mama','Nana'])}),
 Object.freeze({id:'p-k',words:Object.freeze(['Papa','Kaka'])}),
 Object.freeze({id:'v-z',words:Object.freeze(['Vava','Zaza'])})
]);
const MASTER=Object.freeze(PAIRS.flatMap(pair=>pair.words.map((word,i)=>Object.freeze({
 id:`${pair.id}-${i}`,pairId:pair.id,word,options:pair.words
}))));
export const TRIAL_COUNT=MASTER.length;
/** Uses 16 secure random bytes generated by the UI: 8 to change option order,
 * 8 for unbiased-ish small Fisher-Yates shuffle. No participant identifiers.
 */
export function createPhonemeSession(bytes){
 if(!(bytes instanceof Uint8Array)||bytes.length!==TRIAL_COUNT*2)throw new TypeError('16 rastgele bayt gereklidir.');
 const trials=MASTER.map((m,i)=>({id:m.id,pairId:m.pairId,word:m.word,
  options:(bytes[i]&1)?[m.options[1],m.options[0]]:[...m.options],
  played:false,choice:null}));
 for(let i=trials.length-1;i>0;i--){const j=bytes[TRIAL_COUNT+i]%(i+1);[trials[i],trials[j]]=[trials[j],trials[i]];}
 return {trials};
}
function validate(session){
 if(!session||!Array.isArray(session.trials)||session.trials.length!==TRIAL_COUNT)throw new RangeError('Geçersiz deneme durumu.');
 const seen=new Set();
 for(const t of session.trials){
  const base=MASTER.find(m=>m.id===t.id);
  if(!base||seen.has(t.id)||base.word!==t.word||base.pairId!==t.pairId||
   !Array.isArray(t.options)||t.options.length!==2||
   !(t.options[0]===base.options[0]&&t.options[1]===base.options[1]||t.options[0]===base.options[1]&&t.options[1]===base.options[0])||
   typeof t.played!=='boolean'||!(t.choice===null||t.options.includes(t.choice)))
   throw new RangeError('Deneme verisi geçersiz.');
  seen.add(t.id);
 }
}
export function markPhonemePlayback(session,id){
 validate(session);const trial=session.trials.find(t=>t.id===id);
 if(!trial||trial.choice!==null)throw new RangeError('Ses örneği değiştirilemez.');
 trial.played=true;
}
export function submitPhonemeChoice(session,id,choice){
 validate(session);const trial=session.trials.find(t=>t.id===id);
 if(!trial||!trial.played||trial.choice!==null||!trial.options.includes(choice))
  throw new RangeError('Önce sesi sonuna kadar dinleyip geçerli tek seçenek seçiniz.');
 trial.choice=choice;
}
/** Export only compact counts. Never expose per-trial answers, target labels, order,
 * words, names, timestamps, browser metadata, source audio or user supplied text.
 */
export function summarizePhonemeSession(session){
 validate(session);
 const categories=Object.fromEntries(PAIRS.map(p=>[p.id,{answered:0,correct:0}]));
 let answered=0,correct=0;
 for(const trial of session.trials){
  if(trial.choice===null)continue;
  answered++;categories[trial.pairId].answered++;
  if(trial.choice===trial.word){correct++;categories[trial.pairId].correct++;}
 }
 return {schema:'dou-phoneme-forced-choice-v1',syntheticOnly:true,
  totalTrials:TRIAL_COUNT,answered,correct,incorrect:answered-correct,
  pairCounts:categories,unvalidatedToyExercise:true,noPersonalDataCollected:true};
}

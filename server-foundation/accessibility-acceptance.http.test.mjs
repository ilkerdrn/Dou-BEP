import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createServer} from 'node:http';
import {openStore} from './institutional-store.mjs';
import {createApiHandler} from './institutional-api.mjs';
import {ACCEPTANCE_CHECKS} from './accessibility-acceptance.mjs';
import {createDemo} from '../core.mjs';
const pwd='AcceptanceHttpPassword-2026!!';
const payload=(phase,revision=1)=>({revision,confirmed:true,checks:Object.fromEntries(ACCEPTANCE_CHECKS[phase].map(([key])=>[key,true]))});
test('v2.34 HTTP acceptance enforces session, CSRF, role, tenant, revision, and independently signed phases',async()=>{
 const dir=mkdtempSync(join(tmpdir(),'bep-acc-http-')),store=openStore(join(dir,'local.sqlite'));
 store.createTenantAdmin({tenantId:'univ-aa',tenantName:'Üniversite AA',email:'admin@aa.test',password:pwd});
 store.createTenantAdmin({tenantId:'univ-bb',tenantName:'Üniversite BB',email:'admin@bb.test',password:pwd});
 const admin=store.signIn({tenantId:'univ-aa',email:'admin@aa.test',password:pwd});const actor=store.requireActor(admin.token);
 store.addMember(actor,{email:'teacher@aa.test',role:'teacher',password:pwd});
 store.addMember(actor,{email:'coord@aa.test',role:'coordinator',password:pwd});
 const teacher=store.signIn({tenantId:'univ-aa',email:'teacher@aa.test',password:pwd});const coordinator=store.signIn({tenantId:'univ-aa',email:'coord@aa.test',password:pwd});
 const other=store.signIn({tenantId:'univ-bb',email:'admin@bb.test',password:pwd});
 const demo=createDemo();demo.profile='';demo.questions=demo.questions.map(q=>({...q,teacherNote:''}));
 const created=store.createExam(store.requireActor(teacher.token),{exam:demo});store.approveExam(actor,created.id,{revision:1,confirmed:true});
 let handler;const server=createServer((req,res)=>handler(req,res,new URL(req.url,'http://localhost').pathname));
 try{await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));handler=createApiHandler(store,{port:server.address().port});const origin=`http://127.0.0.1:${server.address().port}`;
  const call=(path,auth,phase,csrf)=>fetch(origin+path,{method:phase?'POST':'GET',headers:{...(auth?{Cookie:`bep_session=${auth.token}`}:{}) ,...(phase?{'Content-Type':'application/json','X-CSRF-Token':csrf||''}:{})},body:phase?JSON.stringify(payload(phase)):undefined});
  assert.equal((await call('/api/acceptance/exams')).status,401);
  assert.equal((await call(`/api/acceptance/exams/${created.id}`,other)).status,404);
  assert.equal((await call('/api/acceptance/exams',other)).status,200);
  assert.equal((await call('/api/acceptance/exams',teacher)).status,200);
  assert.equal((await call(`/api/acceptance/exams/${created.id}/teacher`,teacher,'teacher')).status,403);
  assert.equal((await call(`/api/acceptance/exams/${created.id}/teacher`,admin,'teacher',admin.csrf)).status,403);
  assert.equal((await call(`/api/acceptance/exams/${created.id}/teacher`,teacher,'teacher',teacher.csrf)).status,200);
  assert.equal((await call(`/api/acceptance/exams/${created.id}/coordinator`,teacher,'coordinator',teacher.csrf)).status,403);
  assert.equal((await call(`/api/acceptance/exams/${created.id}/coordinator`,coordinator,'coordinator',coordinator.csrf)).status,200);
  const received=await (await call(`/api/acceptance/exams/${created.id}`,teacher)).json();assert.equal(received.acceptanceStatus,'reviewed');
  assert.equal(received.productionReady,false);assert.equal(JSON.stringify(received).includes('question_equivalence'),false);
 }finally{await new Promise(resolve=>server.close(resolve));store.db.close();rmSync(dir,{recursive:true,force:true});}
});
